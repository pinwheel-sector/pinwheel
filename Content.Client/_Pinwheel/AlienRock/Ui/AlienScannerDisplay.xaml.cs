using Content.Client.UserInterface.Controls;
using Content.Shared._Pinwheel.AlienRock;
using Content.Shared._Pinwheel.AlienRock.Equipment;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Pinwheel.AlienRock.Ui;

[GenerateTypedNameReferences]
public sealed partial class AlienScannerDisplay : FancyWindow
{
    [Dependency] private IEntityManager _ent = default!;
    [Dependency] private IGameTiming _timing= default!;

    private EntityUid _owner;
    private TimeSpan? _updateNext;
    private TimeSpan _updateRate;
    private List<string> _nodeNames = new();

    public AlienScannerDisplay()
    {
        RobustXamlLoader.Load(this);

        IoCManager.InjectDependencies(this);
    }

    public void SetOwner(EntityUid uid)
    {
        if (!_ent.TryGetComponent<AlienScannerComponent>(uid, out var comp))
            return;

        _updateRate = comp.UiUpdateRate;
        _owner = uid;
    }

    /// <inheritdoc />
    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_updateNext != null
            && _updateNext > _timing.CurTime)
            return;

        _updateNext = _timing.CurTime + _updateRate;

        if (!_ent.TryGetComponent<AlienScannerConnectedComponent>(_owner, out var con)
            || !_ent.TryGetComponent<AlienRockComponent>(con.Attached, out var rock))
        { // set text with empty node list if we're not connected
            var empty = new List<string>();
            SetText(false, empty);
            return;
        }

        if (rock.Nodes is null)
            throw new Exception("Artifact does not have a node container");

        _nodeNames.Clear();

        var nodeList = rock.Nodes.ContainedEntities;

        foreach (var uid in nodeList)
        {
            var node = _ent.GetNetEntity(uid);
            _ent.TryGetEntityData(node, out var _, out var nodeMeta);
            _nodeNames.Add(nodeMeta!.EntityDescription);
        }

        SetText(true, _nodeNames);
    }

    private void SetText(
        bool connected,
        List<string> nodes)
    {
        ScannerStateLabel.Text = connected
            ? Loc.GetString("alienrock-scanner-info-connected")
            : Loc.GetString("alienrock-scanner-info-disconnected");

        NodesList.Children.Clear();

        if (nodes.Count > 0)
        {
            // show list of triggered nodes instead of 'no data' placeholder
            NodesClearedLabel.Visible = false;
            NodesList.Visible = true;

            foreach (var node in nodes)
            {
                var nodeLabel = new Button
                { // using buttons for this is stupid but i cba making it look good because i don't know UI
                    Text = node,
                    Margin = new Thickness(15, 5, 0, 0),
                    MaxHeight = 40,
                    Disabled = true,
                };
                NodesList.Children.Add(nodeLabel);
            }
        }
        else
        {
            // clear list of activated nodes (done previously), show 'no data' placeholder
            NodesClearedLabel.Visible = true;
            NodesList.Visible = false;
        }
    }
}
